import { expect, test } from '@playwright/test'

test('real Go/Python training prepares only start, trades incrementally, pauses, views history and resets date', async ({page,request})=>{
  test.skip(process.env.TVBT_TRAINING_LIVE !== '1','Requires live Go/Python and standardized AOL9 data')
  const listing=await (await request.get('/api/v1/datasets')).json()
  const listed=listing.datasets.find((d:{dataset_id:string})=>d.dataset_id==='SHFE.AOL9.5m')
  expect(listed).toBeTruthy()
  const dataset=await (await request.get(`/api/v1/datasets/${listed.dataset_id}?revision=${encodeURIComponent(listed.active_revision)}`)).json()
  await page.addInitScript(dataset=>Object.assign(window,{simulationFixtureProps:{dataset,indicatorSources:[],strategySources:[],replayCursor:null,replayObjects:null,replaySignals:[]}}),dataset)
  const errors:string[]=[]
  page.on('pageerror',error=>errors.push(error.message))
  page.on('console',message=>{if(message.type()==='error')errors.push(message.text())})
  const submitted:string[]=[]
  page.on('request',request=>{if(request.method()==='POST'&&request.url().includes('/commands'))submitted.push(request.postDataJSON().action)})
  await page.goto('/e2e/divergence-simulation.html')
  const panel=page.getByLabel('三类背驰自动交易模拟'),chart=page.getByLabel('K 线多窗格图表')
  await panel.getByLabel('结束K',{exact:true}).fill('1000')
  const createdPromise=page.waitForResponse(response=>response.request().method()==='POST'&&new URL(response.url()).pathname==='/api/v1/training-sessions')
  await panel.getByRole('button',{name:'开始自动交易模拟',exact:true}).click()
  const accepted=await (await createdPromise).json()
  await expect(panel).toContainText('逐根训练')
  await expect(chart).toHaveAttribute('data-cache-last-index','0')
  const prepared=await (await request.get(`/api/v1/training-sessions/${accepted.session_id}`)).json()
  expect(prepared.snapshot.processed_until_bar_index).toBe(0)
  expect(submitted).toEqual([])
  await page.getByRole('button',{name:'单步',exact:true}).click()
  await expect(chart).toHaveAttribute('data-cache-last-index','1')
  await page.getByRole('button',{name:'播放模拟',exact:true}).click()
  await expect.poll(async()=>Number(await chart.getAttribute('data-cache-last-index'))).toBeGreaterThan(1)
  await page.getByRole('button',{name:'暂停模拟',exact:true}).click()
  await expect(panel.getByRole('button',{name:'跳转',exact:true})).toBeEnabled()
  const before=await (await request.get(`/api/v1/training-sessions/${accepted.session_id}`)).json()
  const frozen=before.snapshot.processed_until_bar_index, commandCount=submitted.length
  await expect.poll(async()=>{
    const state=await (await request.get(`/api/v1/training-sessions/${accepted.session_id}`)).json()
    expect(state.snapshot.processed_until_bar_index).toBe(frozen)
    return state.snapshot.cursor
  }).toBe(frozen)
  expect(submitted.length).toBe(commandCount)
  await panel.getByLabel('模拟跳转K线').fill('1000')
  await panel.getByRole('button',{name:'跳转',exact:true}).click()
  await expect(panel).toContainText('训练完成',{timeout:90000})
  await expect(chart).toHaveAttribute('data-cache-last-index','1000')
  expect(await panel.locator('tbody tr').count()).toBeGreaterThan(0)
  await expect(chart.locator('.replay-signal').first()).toBeVisible()
  const finished=await (await request.get(`/api/v1/training-sessions/${accepted.session_id}`)).json()
  expect(finished.snapshot.state).toBe('completed')
  expect(finished.snapshot.completed_run_ref).toBe(`runs/${accepted.session_id}`)
  await panel.getByRole('button',{name:'分析报告',exact:true}).click()
  await expect(panel.getByLabel('当前复盘训练分析报告')).toContainText('累计手续费')
  await page.screenshot({path:'../trading-data/acceptance/strategy-training-16b-live.png',fullPage:true})
  await panel.getByLabel('模拟跳转K线').fill('0')
  await panel.getByRole('button',{name:'跳转',exact:true}).click()
  await expect(panel).toContainText('记录回看')
  await expect(panel.locator('tbody tr')).toHaveCount(0)
  await expect(chart).toHaveAttribute('data-cache-last-index','0')
  await panel.getByLabel('复盘训练日期').fill('2024-06-25')
  const changedPromise=page.waitForResponse(response=>response.request().method()==='POST'&&new URL(response.url()).pathname==='/api/v1/training-sessions')
  await panel.getByRole('button',{name:'更换至此日期',exact:true}).click()
  const changed=await (await changedPromise).json()
  expect(changed.session_id).not.toBe(accepted.session_id)
  await expect(panel).toContainText('逐根训练')
  const reset=await (await request.get(`/api/v1/training-sessions/${changed.session_id}`)).json()
  expect(reset.snapshot.cursor).toBe(reset.snapshot.from_bar_index)
  expect(reset.snapshot.account.position_quantity).toBe(0)
  expect(reset.snapshot.account.total_commission_i64).toBe(0)
  await page.getByRole('button',{name:'退出模拟',exact:true}).click()
  await expect(page.getByLabel('K线模拟速度控制')).toHaveCount(0)
  await expect.poll(async()=>{
    const stopped=await (await request.get(`/api/v1/training-sessions/${changed.session_id}`)).json()
    return stopped.snapshot?.state
  }).toBe('cancelled')
  expect(errors).toEqual([])
  console.log(`Live training ${accepted.session_id}, reset ${changed.session_id}`)
})
